# ============================================================================================================ questions
class NeedAnswer(Exception):
    """A question the answers file does not answer. The skill asks the person, writes the answer under `qid` and re-runs."""

    def __init__(self, qid, prompt, kind="text", choices=None, default=NO, context=None, explain=None, error=None):
        super().__init__(qid)
        self.q = {"qid": qid, "prompt": prompt, "kind": kind}
        if choices: self.q["choices"] = list(choices)
        if default is not NO: self.q["default"] = default
        if context is not None: self.q["context"] = context
        if explain: self.q["explain"] = explain
        if error: self.q["error"] = error


class Refusal(Exception):
    """Setup refuses to continue (stage 0: no model route, no managed settings file; a member check)."""


def _parse(kind, v):
    if kind == "bool":
        if isinstance(v, bool): return v
        s = str(v).strip().lower()
        if s in ("y", "yes", "true", "on", "1"): return True
        if s in ("n", "no", "false", "off", "0"): return False
        raise ValueError(f"expected yes or no, got {v!r}")
    if kind == "int": return int(v)
    if kind == "order":   # `confirm`, or a list of positions
        if isinstance(v, str) and v.strip().lower() == "confirm": return "confirm"
        v = json.loads(v) if isinstance(v, str) else v
        return [int(x) for x in v] if isinstance(v, list) else v
    if kind == "list":
        if isinstance(v, list): return [x.strip() if isinstance(x, str) else x for x in v if x not in ("", None)]
        return [x.strip() for x in re.split(r"[;,\n]", str(v)) if x.strip()]
    if kind == "json":
        return json.loads(v) if isinstance(v, str) else v
    return v if not isinstance(v, str) else v.strip()


class Answers:
    """Every question setup asks goes through get(). Sources, in order: the answers (a dict, or a JSON file whose top level is the
    dict or {"answers": dict}); the person (interactive=True: the terminal form; the skill's form is the answers file); the default
    (use_defaults=True only); otherwise NeedAnswer. Each answer is kept in `used` with where it came from."""

    def __init__(self, data=None, path=None, interactive=False, use_defaults=False):
        self.path = path
        if path and os.path.isfile(path):
            with open(path, encoding="utf-8") as f: d = json.load(f)
            data = dict(d.get("answers", d), **(data or {}))
        self.data = dict(data or {})
        self.interactive, self.use_defaults = interactive, use_defaults
        self.used = collections.OrderedDict()

    def has(self, qid): return qid in self.data

    def get(self, qid, prompt, kind="text", choices=None, default=NO, context=None, explain=None, validate=None):
        if qid in self.data:
            v, src = self.data[qid], "answers"
        elif self.interactive:
            if explain: print("\n" + explain)
            if context is not None: print(json.dumps(context, indent=1, ensure_ascii=False)[:6000])
            hint = f" [{', '.join(map(str, choices))}]" if choices else ""
            hint += f" (default: {json.dumps(default, ensure_ascii=False)})" if default is not NO else ""
            raw = input(f"{prompt}{hint}\n> ").strip()
            if not raw and default is not NO: v, src = default, "default (interactive)"
            else: v, src = (json.loads(raw) if kind == "json" else raw), "interactive"
        elif default is not NO and self.use_defaults:
            v, src = default, "default"
        else:
            raise NeedAnswer(qid, prompt, kind, choices, default, context, explain)
        try:
            v = _parse(kind, v)
        except (ValueError, json.JSONDecodeError) as e:
            raise NeedAnswer(qid, prompt, kind, choices, default, context, explain, error=str(e))
        if choices and kind != "list" and v not in choices:
            raise NeedAnswer(qid, prompt, kind, choices, default, context, explain, error=f"{v!r} is not one of {choices}")
        if validate:
            err = validate(v)
            if err: raise NeedAnswer(qid, prompt, kind, choices, default, context, explain, error=err)
        self.used[qid] = {"value": v, "from": src}
        return v


