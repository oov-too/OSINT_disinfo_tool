    def run(self, until=8):
        """Run every stage from the first whose file is missing up to `until`; returns the stages completed now."""
        doneNow = []
        os.makedirs(self.dir(), exist_ok=True)
        n = self.next_stage()
        while n is not None and n <= until:
            getattr(self, f"stage_{n}")()
            doneNow.append(n)
            n = self.next_stage()
        return doneNow

    def rerun(self, n):
        """Re-run one stage (/settings): its earlier answers are the defaults under the new ones."""
        old = self.stage(n).get("answers", {})
        for q, v in old.items():
            if q not in self.answers.data:
                try: self.answers.data[q] = json.loads(v) if isinstance(v, str) and v[:1] in "[{" else v
                except ValueError: self.answers.data[q] = v
        return getattr(self, f"stage_{n}")()

