def _get_dotted(d, key, default=None):
    for part in key.split("."):
        if not isinstance(d, dict) or part not in d: return default
        d = d[part]
    return d


def _merge_into(d, key, value):
    """Set a dotted key, deep-merging a dict value into what is there."""
    parts = key.split("."); cur = d
    for part in parts[:-1]:
        if not isinstance(cur.get(part), dict): cur[part] = {}
        cur = cur[part]
    last = parts[-1]
    if isinstance(value, dict) and isinstance(cur.get(last), dict):
        for k, v in value.items(): _merge_into(cur[last], k, v)
    else:
        cur[last] = value
