def pack_root_of(path):
    """The folder holding a pack.toml at or above `path` (the pack the file belongs to), else None."""
    d = path if os.path.isdir(path) else os.path.dirname(path)
    while True:
        if os.path.isfile(os.path.join(d, "pack.toml")): return d
        up = os.path.dirname(d)
        if up == d: return None
        d = up


def _walk_strings(v, key):
    """(dotted key, string) for every string in a pack value; a list's strings take the list's key."""
    if isinstance(v, dict):
        for k, x in v.items(): yield from _walk_strings(x, f"{key}.{k}" if key else k)
    elif isinstance(v, list):
        for x in v: yield from _walk_strings(x, key)
    elif isinstance(v, str): yield key, v


def actor_row_shape(text):
    """The actor register's row shape a pack's actor_register slot gives the writers: the first backticked table row in the slot text
    that is not the polity statement shape (a header with Inside and Opposed) and opens with `#`, taken when it is an actor table
    (notes.py reads it as one: a Polity and a chain column); else None (7b2 item 23). Nothing else in the wording is read."""
    for m in re.finditer(r"`(\|[^`\n]*\|)`", text or ""):
        cols = LN.split_row(m.group(1))
        if not cols or LN._register_table_kind(cols) == "stm": continue
        return cols if cols[0] == "#" and LN._register_table_kind(cols) == "act" else None
    return None


def keyword_file(head, terms):
    """A keyword list: a comment line, then one term per line (each once, in the order given)."""
    seen, out = set(), []
    for t in terms:
        t = str(t).strip()
        if t and t.lower() not in seen: seen.add(t.lower()); out.append(t)
    return f"# {head}\n" + "\n".join(out) + ("\n" if out else "")


