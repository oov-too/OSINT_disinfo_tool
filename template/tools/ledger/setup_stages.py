    def pack_check(self, run_toml=None):
        """The pack loads through tools/packload.py (a fresh copy pointed at this project) and the intake briefs render with no missing slot.
        `run_toml`: the run whose values fill {{run.*}} (stage 8's run; the pack-check command gives a check-only run before stage 8)."""
        import importlib.util
        probs = []
        src = self.p("tools", "packload.py") if os.path.isfile(self.p("tools", "packload.py")) else os.path.join(self.tools_project, "tools", "packload.py")
        spec = importlib.util.spec_from_file_location("packload_setup_check", src)
        PL = importlib.util.module_from_spec(spec); spec.loader.exec_module(PL)
        PL.ROOT = self.project; PL.LEDGER_FILE = self.p("ledger.toml"); PL._cache.clear()
        calls = [("pack", lambda: PL.pack()), ("audited_subjects", PL.audited_subjects), ("all_subjects", PL.all_subjects),
                 ("eras(pages)", lambda: PL.eras("pages")), ("eras(synchrony)", lambda: PL.eras("synchrony")), ("eras(map)", lambda: PL.eras("map")),
                 ("source_kinds", PL.source_kinds), ("stem_patterns", PL.stem_patterns), ("topics", PL.topics), ("audit_captions", PL.audit_captions),
                 ("objects", PL.objects), ("threshold_label", PL.threshold_label), ("id_patterns", PL.id_patterns), ("theses", PL.theses),
                 ("pirs", PL.pirs), ("actor_vocabulary", PL.actor_vocabulary), ("skeleton_forms", lambda: PL.skeleton_forms()[0]), ("display(status)", lambda: PL.display("status")), ("ledger_title", PL.ledger_title)]
        if hasattr(PL, "tool_data"):   # the core tools' domain data (phase 7b): every tool's defaults with the pack's keys laid over them
            calls.append(("tool_data", lambda: [PL.tool_data(t) for t in PL.TOOL_DEFAULTS]))
        results = {}
        for name, f in calls:
            try:
                v = f(); results[name] = "ok" if name == "pack" else (v if isinstance(v, (str, int)) else len(v))
            except Exception as e:
                probs.append(f"packload.{name}: {e.__class__.__name__}: {e}"); results[name] = "FAILED"
        for inst in PL.pack().get("lenses", {}).get("instance", []):
            try: PL.lens_instance(inst["id"])
            except Exception as e: probs.append(f"packload.lens_instance({inst['id']}): {e}")
        r = BR.render(self.project, None, run_toml or self.run_toml_path(), ["operations.md", "intake-", "staged/"], None, None, False, True)
        if r["missing"]: probs.append("brief slots without a value: " + ", ".join(r["missing"]))
        return {"ok": not probs, "problems": probs, "packload": results, "briefs_rendered": r["n"], "slots_from_pack": len(r["from_pack"]),
                "slots_from_defaults": len(r["from_defaults"]), "templates": r["templates"]}

