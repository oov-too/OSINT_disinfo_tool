    @staticmethod
    def _words(s):
        stop = {"a", "an", "the", "and", "or", "of", "to", "in", "on", "is", "are", "be", "by", "for", "with", "that", "this", "it", "as", "at",
                "who", "what", "which", "their", "they", "them", "its", "from", "does", "do", "not", "no", "than", "more", "one", "any", "so", "into"}
        return {w for w in re.findall(r"[a-z]+", s.lower()) if w not in stop and len(w) > 2}

    def map_technique(self, statement, criteria):
        """[(score, criterion id, statement)] for one technique against the catalogue, by shared content words (Jaccard on stems)."""
        stem = lambda ws: {w[:6] for w in ws}
        tw = stem(self._words(statement)); out = []
        for c in criteria:
            cw = stem(self._words(re.sub(r"\{[a-z_]+\}", " ", c["statement"])))
            if tw and cw: out.append((round(len(tw & cw) / len(tw | cw), 3), c["id"], c["statement"]))
        return sorted(out, reverse=True)[:3]

