    def import_files(self, n, pack, slots):
        """Copy every file or folder a pack value names under another pack (a folder holding a pack.toml that is not this pack's)
        into this pack at the same place under the pack's folder, repoint the value and the slot texts naming it, and record the
        provenance (setup/imports.json and the stage file). The files setup writes from the answers (FROM_ANSWERS) are not copied."""
        own = os.path.realpath(self.pack_dir())
        ledger_ = self.imports(); swaps = []

        def copy(src, root):
            tail = os.path.relpath(src, root).replace(os.sep, "/")
            dest = self.p(*self.pack_rel(*tail.split("/")).split("/"))
            os.makedirs(os.path.dirname(dest), exist_ok=True); shutil.copyfile(src, dest)
            return tail

        def visit(v, key):
            if isinstance(v, dict): return {k: visit(x, f"{key}.{k}" if key else k) for k, x in v.items()}
            if isinstance(v, list): return [visit(x, key) for x in v]
            if not isinstance(v, str) or not v.strip() or "\n" in v or len(v) > 600 or key in PACK_FIXED: return v
            given = v.strip(); src = os.path.expanduser(given)
            src = os.path.realpath(src if os.path.isabs(src) else self.p(*src.split("/")))
            if not os.path.exists(src): return v
            root = pack_root_of(src)
            if not root or os.path.realpath(root) == own: return v
            root = os.path.realpath(root); tail = os.path.relpath(src, root).replace(os.sep, "/")
            if tail == ".": return v
            if tail in FROM_ANSWERS: return self.pack_rel(*tail.split("/"))   # this pack's own file of that name, written from the answers
            if os.path.isdir(src):
                files = []
                for dp, dns, fs in os.walk(src):
                    dns[:] = sorted(d for d in dns if d != "__pycache__")
                    for f in sorted(fs):
                        t = os.path.relpath(os.path.join(dp, f), root).replace(os.sep, "/")
                        if t not in FROM_ANSWERS and t != "pack.toml": files.append(copy(os.path.join(dp, f), root))
                rec = {"kind": "folder", "files": len(files)}
            else:
                copy(src, root)
                with open(src, "rb") as f: data = f.read()
                rec = {"kind": "file", "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
            rel = self.pack_rel(*tail.split("/"))
            rec.update({"key": key, "from": D_redact(src), "given": D_redact(given), "pack": D_redact(root), "stage": n, "imported": today(), "by": self.author()})
            ledger_[rel] = rec; self._imported_now.append(dict(rec, to=rel))
            swaps.append((given, rel))
            if root.startswith(os.path.realpath(self.project) + os.sep):   # the source pack is this project's: its relative name too
                swaps.append((os.path.relpath(src, os.path.realpath(self.project)).replace(os.sep, "/"), rel))
            return rel

        for sec in list(pack):
            pack[sec] = visit(pack[sec], sec)
        # 7b2 item 2 (pilot-1023 finding 2): the files of a source pack that no answered key names are brought too: every pack-relative
        # path a slot of this stage names in the source pack's briefs/slots.toml (or in this stage's slot texts), and every pack-relative
        # path a value of this stage's sections holds in the source pack's pack.toml (when this pack's key is unset or names the same place)
        recorded = len(self._imported_now)
        for root in self.source_packs():
            spk = load_toml(os.path.join(root, "pack.toml")); prefix = self.source_prefix(root, spk)
            src_slots = load_toml(os.path.join(root, "briefs", "slots.toml")).get("slots", {})
            for k in sorted(set(src_slots) | set(slots)):
                if SLOT_STAGE.get(k, OTHER_SECTIONS_STAGE) != n: continue
                for text in (src_slots.get(k), slots.get(k)):
                    for tail in self.prefixed_tails(text, prefix):
                        for t, given in self.bring(root, prefix, tail, f"slot {k}", "briefs/slots.toml", n, ledger_):
                            swaps.append((given, self.pack_rel(*t.split("/"))))
            named = {s for secs in PACK_SECTIONS.values() for s in secs}
            secs = [s for s in spk if s in PACK_SECTIONS.get(n, []) or (n == OTHER_SECTIONS_STAGE and s not in named)]
            for sec in secs:
                for key, v in _walk_strings(spk.get(sec), sec):
                    if key in PACK_FIXED or not v.startswith(prefix + "/"): continue
                    tail = v[len(prefix) + 1:].strip().rstrip("/")
                    mine = _get_dotted(pack, key)
                    own_rel = self.pack_rel(*tail.split("/"))
                    if mine is not None and own_rel not in (mine if isinstance(mine, list) else [mine]): continue   # the answers chose otherwise
                    for t, given in self.bring(root, prefix, tail, key, "pack.toml", n, ledger_):
                        swaps.append((given, self.pack_rel(*t.split("/"))))
        if swaps:
            for k, s in list(slots.items()):
                for a, b in sorted(swaps, key=lambda x: -len(x[0])):
                    if a and a != b and isinstance(s, str): s = s.replace(a, b)
                slots[k] = s
        if swaps or len(self._imported_now) > recorded:
            write_json(self.dir("imports.json"), ledger_)
        return swaps

    def source_packs(self):
        """The packs the answers import from: every folder holding a pack.toml (not this pack's) under which an answer value, anywhere
        in the answers file, names an existing file or folder (by an absolute path or one relative to the project), in the order met."""
        try: own = os.path.realpath(self.pack_dir())
        except RuntimeError: own = None
        out = []
        def look(v):
            if isinstance(v, dict):
                for x in v.values(): look(x)
            elif isinstance(v, list):
                for x in v: look(x)
            elif isinstance(v, str) and v.strip() and "\n" not in v and len(v) <= 600 and "/" in v:
                s = os.path.expanduser(v.strip())
                s = os.path.realpath(s if os.path.isabs(s) else self.p(*s.split("/")))
                if not os.path.exists(s): return
                root = pack_root_of(s)
                if root and os.path.realpath(root) != own and os.path.realpath(root) not in out: out.append(os.path.realpath(root))
        look(self.answers.data)
        return out

    @staticmethod
    def source_prefix(root, spk=None):
        """How the source pack's own texts name its files: its pack.toml [pack] root (packs/<name>), else packs/<its folder name>."""
        spk = spk if spk is not None else load_toml(os.path.join(root, "pack.toml"))
        return (str(spk.get("pack", {}).get("root") or "").strip().rstrip("/")) or "packs/" + os.path.basename(root)

    @staticmethod
    def prefixed_tails(text, prefix):
        """The pack-relative tails of every `<prefix>/<path>` a text names (a placeholder such as <id> skipped)."""
        if not isinstance(text, str) or not prefix: return []
        out = []
        for m in re.finditer(r"(?<![A-Za-z0-9_./-])" + re.escape(prefix) + r"/([A-Za-z0-9_./-]+)", text):
            t = m.group(1).rstrip(".,;:/-")
            if t and t not in out: out.append(t)
        return out

    def bring(self, root, prefix, tail, key, named_in, n, ledger_):
        """Import the source pack's file (or each file of its folder) at `tail` into this pack at the same place, with the guards of a
        generated file: never a file setup writes from the answers, never through a path whose real location leaves this pack or the
        project, never over a pack file edited since setup wrote or imported it (kept, and listed in the stage file). Returns the
        [(tail, the name as the source pack gives it)] brought now."""
        src = os.path.realpath(os.path.join(root, *tail.split("/")))
        if not (src == root or src.startswith(root + os.sep)) or not os.path.exists(src) or src == root: return []
        files = []
        if os.path.isdir(src):
            for dp, dns, fs in os.walk(src):
                dns[:] = sorted(d for d in dns if d != "__pycache__")
                files += [os.path.join(dp, f) for f in sorted(fs)]
        else: files = [src]
        own = os.path.realpath(self.pack_dir()); led = B.read_json(self.dir("generated.json"), {}) or {}; out = []
        for s in files:
            t = os.path.relpath(s, root).replace(os.sep, "/")
            if t in FROM_ANSWERS or t == "pack.toml": continue
            rel = self.pack_rel(*t.split("/")); dest = self.p(*rel.split("/"))
            if any(r.get("to") == rel and r.get("pack") != D_redact(root) for r in self._imported_now): continue   # another source's, this stage
            real = os.path.realpath(dest if os.path.exists(dest) else os.path.dirname(dest))
            while not os.path.exists(real) and real != os.path.dirname(real): real = os.path.dirname(real)
            if not self.inside(dest) or not (real == own or real.startswith(own + os.sep) or own.startswith(real + os.sep)): continue
            with open(s, "rb") as f: data = f.read()
            sha = hashlib.sha256(data).hexdigest()
            if os.path.isfile(dest):
                with open(dest, "rb") as f: cur = hashlib.sha256(f.read()).hexdigest()
                prev = ledger_.get(rel, {})
                if cur == sha and (prev.get("sha256") == sha or self.imported(rel)): continue   # already imported, unchanged
                if cur != sha and cur != led.get(rel) and cur != prev.get("sha256"):
                    self._import_kept.append({"to": rel, "from": D_redact(s), "why": "edited since setup wrote it: kept"}); continue
            elif os.path.exists(dest): continue
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            with open(dest, "wb") as f: f.write(data)
            rec = {"kind": "file", "bytes": len(data), "sha256": sha, "key": key, "named_in": named_in, "from": D_redact(s),
                   "given": f"{prefix}/{t}", "pack": D_redact(root), "stage": n, "imported": today(), "by": self.author()}
            ledger_[rel] = rec; self._imported_now.append(dict(rec, to=rel)); out.append((t, f"{prefix}/{t}"))
        return out

    def import_seed(self, pack, key, tail):
        """A seed the source pack holds is imported, never generated empty over it (7b2 item 2): the file the source pack's own `key`
        names, when this pack's key is unset or names the same place. Returns whether a source pack supplied it."""
        for root in self.source_packs():
            spk = load_toml(os.path.join(root, "pack.toml")); prefix = self.source_prefix(root, spk)
            v = _get_dotted(spk, key)
            if not isinstance(v, str) or not v.startswith(prefix + "/"): continue
            t = v[len(prefix) + 1:].strip(); mine = _get_dotted(pack, key)
            if mine is not None and mine != self.pack_rel(*t.split("/")): continue
            if not os.path.isfile(os.path.join(root, *t.split("/"))): continue
            ledger_ = self.imports()
            got = self.bring(root, prefix, t, key, "pack.toml", 1, ledger_)
            if got: write_json(self.dir("imports.json"), ledger_)
            if mine is None: _merge_into(pack, key, self.pack_rel(*t.split("/")))
            if got or self.imported(self.pack_rel(*t.split("/"))): return True
        return False

    def inside(self, path):
        """Whether `path`, symbolic links resolved, lies in the project folder (setup never writes through a link out of it)."""
        real = os.path.realpath(path if os.path.exists(path) else os.path.dirname(path))
        root = os.path.realpath(self.project)
        return real == root or real.startswith(root + os.sep)

    def gen(self, rel, text, page=False):
        """Write a generated file at the project-relative `rel`. Never: an imported file; a path under another pack; a path whose real
        location is outside the project folder; a file outside this pack that exists already (a project page or tool file: written
        only when absent; `page` asks the same of a file inside the pack, for seeds later tools fill); a pack file edited since setup
        generated it (setup/generated.json keeps what setup wrote). Returns whether the file holds the text."""
        rel = rel.replace(os.sep, "/").strip()
        if not rel or os.path.isabs(rel) or rel.startswith("../") or self.imported(rel): return False
        if rel.startswith("packs/") and not rel.startswith(self.pack_rel() + "/"): return False
        path = self.p(*rel.split("/"))
        if not self.inside(path): return False
        own = rel.startswith(self.pack_rel() + "/")
        if (page or not own) and os.path.exists(path): return False
        new = text if text.endswith("\n") else text + "\n"
        led = B.read_json(self.dir("generated.json"), {}) or {}
        if os.path.isfile(path):
            with open(path, "rb") as f: cur = f.read()
            if cur == new.encode("utf-8"): return True   # unchanged: not rewritten, not recorded again
            if rel in led and hashlib.sha256(cur).hexdigest() != led[rel]: return False   # edited since setup wrote it: kept
        write(path, new)
        with open(path, "rb") as f: led[rel] = hashlib.sha256(f.read()).hexdigest()
        write_json(self.dir("generated.json"), led)
        self._generated.append(rel)
        return True

    def key_path(self, pack, key, tail):
        """The path the pack's `key` names; when the pack lacks the key, this pack's `tail` (set in the pack, so the key names the file).
        A key given empty names no file, and nothing is generated for it."""
        v = _get_dotted(pack, key)
        if v is None:
            v = self.pack_rel(*tail.split("/")); _merge_into(pack, key, v)
        return v

