def _extractors():
    """tools/context_pack.py's extractors, imported with the project's pack identifier forms left out (a new project has no pack yet,
    and a pack's forms belong to its own scan; the core's generic forms stay)."""
    if "context_pack" in sys.modules: return sys.modules["context_pack"]
    import packload
    orig = packload.id_patterns
    packload.id_patterns = lambda: []
    try:
        import context_pack
    finally:
        packload.id_patterns = orig
    return context_pack


def hold_folders(root):
    """Every hold folder under `root` (a folder whose hold.json is the record: tools/hold-schema.md), in path order; a hold folder's
    own subfolders are not searched."""
    out = []
    for dp, dns, fs in os.walk(root):
        dns.sort()
        if "hold.json" in fs: out.append(dp); dns[:] = []
    return out


def is_hold_source(source):
    """A stage 2 source that is a folder of holds (`holds:<folder>`, or a folder with hold.json files under it), not a database."""
    s = str(source or "")
    if s.startswith("holds:"): return True
    p = os.path.abspath(os.path.expanduser(s))
    return os.path.isdir(p) and not s.startswith(("csv:", "sqlite:")) and bool(hold_folders(p))


def D_redact(path):
    """A path for the pack and the stage files: the home folder written as ~ (the setup files name no user's home)."""
    home = os.path.expanduser("~")
    return "~" + path[len(home):] if path == home or path.startswith(home + os.sep) else path


def held_records(project, db, folders=None):
    """[(identifier, hold folder relative, record dict, text, annotations list)] for every record held under sources/db/<db>/, or
    for each hold folder in `folders` (a hold-folder source, stage 2)."""
    out = []
    base = os.path.join(project, "sources", "db", db)
    for hj in ([os.path.join(f, "hold.json") for f in folders] if folders is not None else sorted(glob.glob(os.path.join(base, "*", "hold.json")))):
        folder = os.path.dirname(hj)
        h = B.read_json(hj, {})
        rec = h.get("record", {})
        parts = []
        names = [rec["text"]] if rec.get("text") else [f["name"] for f in h.get("files", []) if f.get("role") == "derived"
                                                        and f.get("name", "").endswith((".md", ".txt")) and f["name"] != "README.md"]
        for nm in names:
            p = os.path.join(folder, nm)
            if os.path.isfile(p): parts.append(LN.read_text(p, errors="replace"))
        ann = []
        ap = os.path.join(folder, "annotations.json")
        if os.path.isfile(ap): ann = B.read_json(ap, []) or []
        if isinstance(ann, dict): ann = ann.get("rows", ann.get("annotations", []))
        out.append((rec.get("identifier"), os.path.relpath(folder, project).replace(os.sep, "/"), rec, "\n\n".join(parts), ann))
    return out


def _sentences(text):
    return [s.strip() for s in re.split(r"(?<=[.!?])\s+|\n{2,}", text) if s.strip()]


def scan(project, db, pirs=None, folders=None):
    """The setup scan over the hold: names, organisations and dates by the context-pack extractors; the organisation and grouping
    pass (multi-word names, acronym expansion, alias merge, order-of-battle verbs); speakers; actors, polities and placements proposed
    with counts and the records that name them; adverse position markers; PIR terms surfaced. Nothing is placed: these are candidates."""
    CP = _extractors()
    recs = held_records(project, db, folders)
    names_by_rec, dates = {}, collections.Counter()
    all_text = []
    # a person lexicon for a project with no notes yet: the records' speakers and authors, the annotations' attributions, and names
    # the text itself gives a role ("Desmond Harlowe, chief executive of ..."); context_pack's grouping marks these as people
    lexicon = set()
    for ident, hold, rec, text, ann in recs:
        for n in list(rec.get("speaker_or_author") or []) + [a.get("attributed_to") for a in ann if isinstance(a, dict) and a.get("attributed_to")]:
            toks = [t for t in CP.norm_tokens(n) if t not in CP.TITLES]
            if 2 <= len(toks) <= 4: lexicon.add(" ".join(toks))
        for m in PERSON_CONTEXT.finditer(text):
            toks = [t for t in CP.norm_tokens(m.group(1) or m.group(2)) if t not in CP.TITLES]
            while toks and toks[0] in CP.STOP: toks.pop(0)   # "In March Desmond Harlowe," -> desmond harlowe
            if 2 <= len(toks) <= 4 and not set(toks) & ORG_WORDS: lexicon.add(" ".join(toks))
    by_last = collections.defaultdict(set)
    for n in lexicon: by_last[n.split()[-1]].add(n)
    for ident, hold, rec, text, ann in recs:
        blob = "\n\n".join([rec.get("title") or "", text] + [str(a.get("text") or a.get("body") or "") for a in ann if isinstance(a, dict)])
        all_text.append(blob)
        names, lower_vocab = CP.extract_names(blob, 1, frozenset(lexicon))
        items = CP.group_names(names, lexicon, by_last, {}, lower_vocab)
        names_by_rec[ident] = {it["display"]: it for it in items}
        full, my, years, _ = CP.extract_dates(blob)
        for k, n in full.items(): dates[k] += n
        if rec.get("date"): dates[str(rec["date"]).rstrip("?")] += 0
    # merge candidates across records
    cand = {}
    for ident, items in names_by_rec.items():
        for disp, it in items.items():
            c = cand.setdefault(disp, {"name": disp, "kind": it["kind"], "count": 0, "records": [], "variants": set(), "aliases": set()})
            c["count"] += it["count"]; c["records"].append(ident); c["variants"] |= set(it["variants"])
            c["aliases"] |= {m for m in it.get("members", ()) if m != disp}
            if it["kind"] == "person": c["kind"] = "person"
    corpus = "\n\n".join(all_text)
    all_norm = [blob.replace("’", "'") for blob in all_text]   # each record's text with curly apostrophes straightened, made once (phase 7b)
    # possessive organisation names the extractor splits at the apostrophe ("the Timber Exporters' League"): join head and tail; the
    # bare tail becomes the alias "the <tail>"
    for m in re.finditer(r"\b((?:[A-Z][\w-]+\s+){0,4}[A-Z][\w-]+)(['’]s?)\s+([A-Z][\w-]+)\b", corpus):
        head, tail = m.group(1), m.group(3)
        if tail.lower() not in ORG_WORDS and tail.lower() not in POLITY_WORDS: continue
        if head.split()[0].lower() in ("the", "a", "an"): head = " ".join(head.split()[1:]) or head
        full = f"{head}{m.group(2).replace('’', chr(39))} {tail}"
        c = cand.setdefault(full, {"name": full, "kind": "organisation", "count": 0, "records": [], "variants": set(), "aliases": set()})
        c["kind"] = "organisation"
        for part in (head, tail):
            if part in cand and part != full and cand[part]["kind"] != "person":
                o = cand.pop(part); c["count"] += o["count"]; c["records"] += o["records"]
                if part == tail: c["aliases"].add(f"the {tail}")
        c["count"] = max(c["count"], 1)
        c["records"] += [r[0] for r, blob in zip(recs, all_norm) if full in blob]
    # acronym expansion: "Long Name (ACR)" anywhere in the hold
    for m in re.finditer(r"\b((?:[A-Z][\w'’&-]+\s+){1,6}[A-Z][\w'’&-]+)\s+\(([A-Z]{2,8})\)", corpus):
        longname, acr = m.group(1).strip(), m.group(2)
        initials = "".join(w[0] for w in longname.split() if w.lower() not in ("of", "the", "and", "for")).upper()
        if initials.endswith(acr) or acr in initials:
            tgt = next((k for k in cand if k == longname or k.endswith(longname) or longname.endswith(k)), None) or longname
            c = cand.setdefault(tgt, {"name": tgt, "kind": "organisation", "count": 0, "records": [], "variants": set(), "aliases": set()})
            c["aliases"].add(acr)
            if acr in cand and acr != tgt:
                o = cand.pop(acr); c["count"] += o["count"]; c["records"] += o["records"]
    # organisation, polity and alias pass ("the <last word>" counted once per distinct last word: phase 7b, a large hold)
    the_count = {}
    for k, c in list(cand.items()):
        toks = k.split(); last = toks[-1].lower().rstrip(".,")
        if c["kind"] != "person" and (last in ORG_WORDS or any(t.lower() in ORG_WORDS for t in toks[1:])) and len(toks) >= 2:
            c["kind"] = "organisation"
        if last in POLITY_WORDS and c["kind"] != "person": c["polity_kind"] = POLITY_WORDS[last]
        if c["kind"] == "organisation" and len(toks) >= 2 and toks[-1][0].isupper():
            short = f"the {toks[-1]}"
            if toks[-1] not in the_count: the_count[toks[-1]] = len(re.findall(r"\b[Tt]he " + re.escape(toks[-1]) + r"\b(?!\s+[A-Z])", corpus))
            n = the_count[toks[-1]]
            if n: c["aliases"].add(short); c["alias_mentions"] = n
    for m in STATE_CONTEXT.finditer(corpus):
        nm = m.group(1).strip()
        c = cand.get(nm) or cand.setdefault(nm, {"name": nm, "kind": "name", "count": 0, "records": [], "variants": set(), "aliases": set()})
        c["polity_kind"] = "state"; c["kind"] = "polity"
    # where each candidate occurs, by record
    for k, c in cand.items():
        c["records"] = sorted(set(c["records"]), key=lambda x: (len(str(x)), str(x)))
    # order-of-battle placements: "<A> is a front for <B>" between two candidates (or an alias), sentence by sentence
    alias_to = {}
    for k, c in cand.items():
        alias_to[k] = k
        for a in c["aliases"]:
            alias_to.setdefault(a, k); alias_to.setdefault(a[0].upper() + a[1:], k)
    names_rx = "|".join(re.escape(n) for n in sorted(alias_to, key=len, reverse=True) if len(n) >= 3)
    placements = {}
    if names_rx:
        verbs_rx = "|".join(re.escape(v) for v, _ in sorted(OOB_VERBS, key=lambda x: -len(x[0])))
        rx = re.compile(r"(?P<a>" + names_rx + r")\b[^.;\n]{0,40}?\b(?P<v>" + verbs_rx + r")\s+(?:the\s+)?(?P<b>" + names_rx + r")\b")
        has_verb = re.compile(r"\b(?:" + verbs_rx + r")\s")   # a placement needs one of the verbs: other sentences are not searched (phase 7b)
        for ident, hold, rec, text, ann in recs:
            blob = (rec.get("title") or "") + "\n\n" + text
            for s in _sentences(blob):
                if not has_verb.search(s): continue
                for m in rx.finditer(s):
                    a, b = alias_to.get(m.group("a"), m.group("a")), alias_to.get(m.group("b"), m.group("b"))
                    if a == b: continue
                    rel = dict(OOB_VERBS)[m.group("v")]
                    p = placements.setdefault((a, rel, b), {"actor": a, "relation": rel, "polity_or_parent": b, "count": 0, "records": [], "evidence": []})
                    p["count"] += 1
                    if ident not in p["records"]: p["records"].append(ident)
                    if len(p["evidence"]) < 3: p["evidence"].append(f"{ident}: {s[:160]}")
                    if rel == "front for": cand[a]["actor_kind"] = "front"
                    if rel == "proxy for": cand[a]["actor_kind"] = "proxy"
    # speakers: the records' speaker_or_author and the annotations' attributed_to (the group's reading, kept apart)
    speakers = {}
    for ident, hold, rec, text, ann in recs:
        for sp in rec.get("speaker_or_author") or []:
            s = speakers.setdefault(sp, {"name": sp, "records": [], "attributed_in_annotations": 0}); s["records"].append(ident)
        for a in ann:
            if isinstance(a, dict) and a.get("attributed_to"):
                s = speakers.setdefault(a["attributed_to"], {"name": a["attributed_to"], "records": [], "attributed_in_annotations": 0})
                s["attributed_in_annotations"] += 1
                if ident not in s["records"]: s["records"].append(ident)
    # actors and polities proposed
    actors, polities = [], []
    for k, c in sorted(cand.items(), key=lambda kv: (-kv[1]["count"], kv[0])):
        row = {"name": k, "count": c["count"], "records": c["records"], "aliases": sorted(c["aliases"]), "detected_as": c["kind"]}
        if c.get("polity_kind"):
            polities.append(dict(row, polity_kind=c["polity_kind"]))
        elif c["kind"] == "person":
            actors.append(dict(row, actor_kind=c.get("actor_kind", "individual")))
        elif c["kind"] in ("organisation", "organisation or programme"):
            actors.append(dict(row, actor_kind=c.get("actor_kind", "non-state actor")))
    # PIR overlay: surface, never place
    pir_terms = [(p.get("id"), t.lower()) for p in (pirs or []) for t in p.get("terms", [])]
    if pir_terms:
        # the corpus's sentences once, and of them only those holding a PIR term, each with the PIRs it holds (phase 7b: a sentence
        # without a term can surface no PIR, and the old form re-split the corpus for every row and term)
        term_sents = []
        for s in _sentences(corpus):
            low = s.lower(); pids = {pid for pid, t in pir_terms if t in low}
            if pids: term_sents.append((s, pids))
        for row in actors + polities:
            hit = sorted({pid for pid, t in pir_terms if t in row["name"].lower() or any(t in a.lower() for a in row["aliases"])})
            sent_hit = sorted({pid for s, pids in term_sents if row["name"] in s for pid in pids})
            if hit or sent_hit: row["pirs"] = sorted(set(hit) | set(sent_hit))
    # adverse position markers per record
    positions = []
    for ident, hold, rec, text, ann in recs:
        low = text.lower(); hits = {mk: low.count(mk) for mk in ADVERSE_MARKERS if mk in low}
        if hits:
            positions.append({"record": ident, "title": rec.get("title"), "venue": rec.get("venue"), "speakers": rec.get("speaker_or_author") or [],
                              "markers": hits, "score": sum(hits.values())})
    positions.sort(key=lambda r: (-r["score"], str(r["record"])))
    # proposals for stage 3: subjects from metadata keyword columns, topics from annotation codes, venues, years
    kw = collections.Counter(); codes = collections.Counter(); venues = collections.Counter(); years = []
    for ident, hold, rec, text, ann in recs:
        md = rec.get("metadata") or {}
        for key, v in md.items():
            if S.synonym_score(key, "metadata") or any(w in key.lower() for w in ("keyword", "tag", "subject", "topic", "categor")):
                for x in re.split(r"[;,]", str(v)):
                    if x.strip(): kw[x.strip().lower()] += 1
        for a in ann:
            if isinstance(a, dict) and a.get("kind"):
                code = str(a["kind"]).split(":", 1)[-1].strip().lower()
                if code: codes[code] += 1
        if rec.get("venue"): venues[rec["venue"]] += 1
        m = re.match(r"(\d{4})", str(rec.get("date") or ""))
        if m: years.append(int(m.group(1)))
    circles = propose_circles(recs, cand)
    # document identifier forms (a capital prefix and a run of digits): the same prefix and length in three mentions or more, two
    # distinct identifiers at least; proposed for the pack's id-patterns.tsv
    id_seen, id_count = collections.defaultdict(set), collections.Counter()
    for m in ID_FORM.finditer(corpus):
        k = (m.group(1), len(m.group(2))); id_seen[k].add(m.group(0)); id_count[k] += 1
    id_forms = [{"prefix": p, "digits": d, "count": id_count[(p, d)], "examples": sorted(id_seen[(p, d)])[:3]}
                for p, d in sorted(id_seen, key=lambda k: (-id_count[k], k)) if id_count[(p, d)] >= 3 and len(id_seen[(p, d)]) >= 2][:20]
    return {"scanned": B.utc_now(), "database": db, "records": len(recs), "identifier_forms": id_forms,
            "record_list": [{"identifier": i, "hold": h, "title": r.get("title"), "date": r.get("date"), "media_kind": r.get("media_kind"),
                             "venue": r.get("venue"), "speakers": r.get("speaker_or_author") or []} for i, h, r, _, _ in recs],
            "names": sorted(({"name": k, "kind": c["kind"], "count": c["count"], "records": c["records"], "aliases": sorted(c["aliases"])} for k, c in cand.items()),
                            key=lambda r: (-r["count"], r["name"])),
            "dates": [{"date": d, "count": n} for d, n in sorted(dates.items())],
            "speakers": sorted(speakers.values(), key=lambda s: (-len(s["records"]), s["name"])),
            "actors": actors, "polities": polities,
            "placements": sorted(placements.values(), key=lambda p: (-p["count"], p["actor"])),
            "adverse_positions": positions,
            "proposals": {"subjects": [{"subject": slug(k, 60), "label": k, "records": n} for k, n in kw.most_common()],
                          "topics": [{"id": slug(k, 60), "label": k, "annotations": n} for k, n in codes.most_common()],
                          "venues": [{"venue": k, "records": n} for k, n in venues.most_common()],
                          "years": sorted(years), "circles": circles, "eras": propose_eras(sorted(years))}}


def propose_circles(recs, cand):
    """Records joined by a shared name (person or organisation named in two records or more): each connected group is a proposed circle."""
    shared = {k for k, c in cand.items() if len(set(c["records"])) >= 2 and c["kind"] in ("person", "organisation", "organisation or programme")}
    parent = {r[0]: r[0] for r in recs}

    def find(x):
        while parent[x] != x: parent[x] = parent[parent[x]]; x = parent[x]
        return x
    for k in shared:
        rs = [r for r in cand[k]["records"] if r in parent]
        for r in rs[1:]: parent[find(r)] = find(rs[0])
    groups = collections.defaultdict(list)
    for r in parent: groups[find(r)].append(r)
    out = []
    for i, (root, members) in enumerate(sorted(groups.items(), key=lambda g: (-len(g[1]), str(g[0]))), 1):
        names = sorted((k for k in shared if set(cand[k]["records"]) & set(members)), key=lambda k: (-cand[k]["count"], k))
        out.append({"id": f"circle-{i}", "label": names[0] if names else f"records {', '.join(map(str, members))}", "records": sorted(members, key=str),
                    "names": names[:12]})
    return out


def propose_eras(years):
    """Up to three eras split at the two widest gaps between the years the records carry; one era when there is no gap."""
    ys = sorted(set(years))
    if not ys: return []
    if len(ys) < 3: return [{"id": f"{ys[0]}-onward", "from": ys[0], "to": 9999}]
    gaps = sorted(((ys[i + 1] - ys[i], i) for i in range(len(ys) - 1)), reverse=True)[:2]
    cuts = sorted(i for g, i in gaps if g > 1)
    eras, lo = [], None
    bounds = [ys[0]] + [ys[i + 1] for i in cuts]
    for j, b in enumerate(bounds):
        hi = bounds[j + 1] - 1 if j + 1 < len(bounds) else 9999
        eras.append({"id": f"{b}-{hi}" if hi != 9999 else f"{b}-onward", "from": b if j else -1000000000, "to": hi if hi != 9999 else 1000000000})
    return eras


