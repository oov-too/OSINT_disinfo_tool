# ============================================================================================================ command line
def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description="The /setup engine: stages 0 to 8")
    ap.add_argument("cmd", choices=["status", "run", "stage", "launched", "pack-check"]); ap.add_argument("n", nargs="?", type=int)
    try: _cwd = os.getcwd()
    except FileNotFoundError: _cwd = os.environ.get("LEDGER_ROOT") or os.path.dirname(os.path.dirname(TOOLS if "TOOLS" in globals() else os.path.dirname(os.path.abspath(__file__))))   # the working folder was deleted under us (2026-10-26)
    ap.add_argument("--project", default=os.environ.get("LEDGER_ROOT") or _cwd); ap.add_argument("--answers")
    ap.add_argument("--until", type=int, default=8); ap.add_argument("--use-defaults", action="store_true"); ap.add_argument("--interactive", action="store_true")
    ap.add_argument("--note"); ap.add_argument("--run"); ap.add_argument("--no-render-test", action="store_true")
    a = ap.parse_args(argv)
    ans = Answers(path=a.answers, interactive=a.interactive, use_defaults=a.use_defaults)
    s = Setup(a.project, ans, render_test=not a.no_render_test)
    if a.cmd == "status":
        for r in s.status(): print(f"stage {r['stage']}\t{'done ' + str(r['completed']) if r['done'] else 'to do'}\t{r['title']}")
        print(f"next: {s.next_stage() if s.next_stage() is not None else 'none (setup complete)'}")
        return 0
    try:
        if a.cmd == "run":
            done = s.run(a.until); print(json.dumps({"completed_now": done, "next": s.next_stage()}))
        elif a.cmd == "stage":
            if a.n is None: ap.error("stage needs N")
            print(s.rerun(a.n) if s.done(a.n) else getattr(s, f"stage_{a.n}")())
        elif a.cmd == "launched":
            print(s.launched(a.note, a.run))
        elif a.cmd == "pack-check":   # the stage 8 pack check on its own (phase 7b): setup/pack-check.json; exit 1 on a problem
            run = s.run_toml_path() if s.pack_name() and os.path.isfile(s.run_toml_path()) else None
            if not run:   # before stage 8: a check-only run under setup/ (never in the pack), with the fields stage 8's run carries
                run = s.dir("pack-check-run.toml")
                write(run, T.dumps({"run": {"label": "pack-check", "date": today(), "purpose": "the pack check before the first intake (no intake runs)",
                                            "brief": "setup/pack-check-run.toml", "flare_documents": "none", "new_material": "none", "new_events": "none"}}))
            r = s.pack_check(run); r["run"] = os.path.relpath(run, s.project); write_json(s.dir("pack-check.json"), r)
            print(json.dumps(r, indent=1, ensure_ascii=False))
            return 0 if r["ok"] else 1
        return 0
    except NeedAnswer as e:
        print(json.dumps(dict(e.q, stage=int(e.q["qid"].split(".")[0]), answers_file=a.answers), indent=1, ensure_ascii=False, default=str)); return 3
    except Refusal as e:
        print(json.dumps({"refused": str(e)}, ensure_ascii=False)); return 4
    except M.Refused as e:
        print(json.dumps({"refused": str(e)}, ensure_ascii=False)); return 4
    except LaunchPending as e:
        print(json.dumps({"launch_pending": e.spec}, indent=1, ensure_ascii=False)); return 5


if __name__ == "__main__":
    sys.exit(main())
