    def core_forms(self):
        """tools/note_skeleton.py's core forms ({form: what it is for}), read from its source (the tool runs at import)."""
        import ast
        for base in (self.project, self.tools_project):
            p = os.path.join(base, "tools", "note_skeleton.py")
            if not os.path.isfile(p): continue
            for node in ast.parse(LN.read_text(p)).body:
                if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) and node.targets[0].id == "CORE_FORMS":
                    return ast.literal_eval(node.value)
        return {"video": "a recording", "document": "a document or a web text", "text": "a single-voice text"}

    def slots_readme(self):
        """The pack's briefs/README.md: every slot with the stage that owns it, its value and whether it is the core default."""
        defaults = BR.slot_values(self.project, None, None, True); slots = self.slots()
        rows = [[k, SLOT_STAGE.get(k, ""), v, "core default" if defaults.get(k, (None,))[0] == v else "this project's answers or scan"]
                for k, v in sorted(slots.items(), key=lambda kv: (SLOT_STAGE.get(kv[0], 9), kv[0]))]
        return (f"# Brief slots of the {self.pack_name()} pack\n\nThe values the brief templates (the plugin's templates/briefs) take for this project, "
                f"written by setup stage by stage into {self.pack_rel('briefs', 'slots.toml')}; a value equal to the core default (templates' "
                "slots-default.toml) is marked so. Change one with /settings, through the stage that owns it.\n\n"
                + md_table(["Slot", "Stage", "Value", "Origin"], rows))

    def freeze(self):
        """Freeze research/platform-baseline.json (tools/build_db.py, then tools/baseline.py) when the project has none, so that `ledger
        check` passes in a new project; a project that already has a baseline keeps it. Returns what happened, for the stage file."""
        if not self.freeze_baseline: return "not frozen (this run did not ask for it)"
        out = self.p("research", "platform-baseline.json")
        if os.path.exists(out): return "kept (the project has one)"
        if not self.inside(out): return "not frozen: research/ lies outside the project folder (a link)"
        tools = self.p("tools") if os.path.isfile(self.p("tools", "baseline.py")) else os.path.join(self.tools_project, "tools")
        env = dict(os.environ, LEDGER_ROOT=self.project)
        for tool in ("build_db.py", "baseline.py"):
            r = subprocess.run([sys.executable, os.path.join(tools, tool)], cwd=self.project, env=env, capture_output=True, text=True)
            if r.returncode != 0: return f"not frozen: {tool} exit {r.returncode}: {(r.stderr or r.stdout).strip()[-300:]}"
        return "frozen: research/platform-baseline.json" if os.path.isfile(out) else "not frozen: tools/baseline.py wrote no file"

