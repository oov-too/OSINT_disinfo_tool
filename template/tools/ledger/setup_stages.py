def read_managed(path):
    rep = {"path": path, "present": bool(path and os.path.isfile(path))}
    if not rep["present"]: return rep
    try:
        with open(path, encoding="utf-8") as f: d = json.load(f)
        rep["keys"] = sorted(d)
        rep["recognised"] = [k for k in MANAGED_KEYS if k in d]
        rep["allowedProviders"] = d.get("allowedProviders")
        rep["availableModels"] = d.get("availableModels")
        rep["maxEffortLevel"] = d.get("maxEffortLevel")
        rep["env_keys"] = sorted((d.get("env") or {}).keys())
        rep["enabledPlugins"] = sorted((d.get("enabledPlugins") or {}).keys())
    except (OSError, ValueError) as e:
        rep["error"] = f"not readable as JSON: {e}"
    return rep


def share_report(path):
    """Whether `path` is on a network share, by the mount table (macOS, Linux) or the drive type (Windows)."""
    p = os.path.realpath(path); system = platform.system()
    rep = {"path": p, "on_share": False, "fstype": "unknown", "mount": None}
    try:
        if system == "Windows":
            if p.startswith("\\\\"): rep.update(on_share=True, fstype="unc")
            else:
                import ctypes
                drive = os.path.splitdrive(p)[0] + "\\"
                t = ctypes.windll.kernel32.GetDriveTypeW(drive)
                rep.update(fstype={2: "removable", 3: "fixed", 4: "network", 5: "cdrom", 6: "ramdisk"}.get(t, str(t)), on_share=(t == 4), mount=drive)
            return rep
        mounts = []
        if system == "Linux" and os.path.isfile("/proc/mounts"):
            for line in open("/proc/mounts", encoding="utf-8", errors="replace"):
                parts = line.split()
                if len(parts) >= 3: mounts.append((parts[1].replace("\\040", " "), parts[2]))
        else:
            out = subprocess.run(["mount"], capture_output=True, text=True, timeout=10).stdout
            for line in out.splitlines():
                m = re.match(r"^.+? on (.+) \(([^,)]+)", line)
                if m: mounts.append((m.group(1), m.group(2).strip()))
        best = max((m for m in mounts if p == m[0] or p.startswith(m[0].rstrip("/") + "/")), key=lambda m: len(m[0]), default=None)
        if best: rep.update(mount=best[0], fstype=best[1], on_share=best[1].lower() in NETWORK_FS)
    except Exception as e:  # the report says so; it never stops setup
        rep["error"] = str(e)
    return rep


def tiny_pdf(path, text="LEDGER OCR TEST 2026"):
    """A one-page PDF with a line of Helvetica text (no dependency), for the test render."""
    content = f"BT /F1 36 Tf 60 400 Td ({text}) Tj ET".encode("ascii")
    objs = [b"<< /Type /Catalog /Pages 2 0 R >>", b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
            b"<< /Length " + str(len(content)).encode() + b" >>\nstream\n" + content + b"\nendstream",
            b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"]
    out = bytearray(b"%PDF-1.4\n"); offs = []
    for i, o in enumerate(objs, 1):
        offs.append(len(out)); out += f"{i} 0 obj\n".encode() + o + b"\nendobj\n"
    x = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode() + b"".join(f"{o:010d} 00000 n \n".encode() for o in offs)
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{x}\n%%EOF\n".encode()
    with open(path, "wb") as f: f.write(bytes(out))
    return path


def quiet(f, *a, **k):
    """Call f with stdout captured: PyMuPDF 1.28 prints a deprecation line to stdout when imported as `fitz`, which would corrupt the
    JSON the command line prints. What was printed is returned beside the result."""
    import contextlib, io
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf): r = f(*a, **k)
    return r, buf.getvalue().strip()


