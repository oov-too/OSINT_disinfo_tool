def detect_route(environ=None):
    """The model route from the environment: names only, never a value."""
    env = environ if environ is not None else os.environ
    on = [(r, v, label) for r, v, label in ROUTES if str(env.get(v, "")).strip() not in ("", "0", "false", "False")]
    rep = {"selectors_set": [v for _, v, _ in on], "routes": [r for r, _, _ in on],
           "gateway_base_url": bool(env.get("ANTHROPIC_BASE_URL")), "api_key_present": bool(env.get("ANTHROPIC_API_KEY") or env.get("ANTHROPIC_AUTH_TOKEN")),
           "overrides_set": [v for v in OVERRIDES if env.get(v)], "proxy": bool(env.get("HTTPS_PROXY") or env.get("https_proxy")),
           "ca_bundle": bool(env.get("NODE_EXTRA_CA_CERTS") or env.get("SSL_CERT_FILE"))}
    if len(on) == 1: rep["route"] = on[0][0]
    elif len(on) > 1: rep["route"] = None; rep["conflict"] = f"more than one provider selector is set: {', '.join(rep['selectors_set'])}"
    elif rep["gateway_base_url"]: rep["route"] = "gateway"
    elif rep["api_key_present"]: rep["route"] = "anthropic"
    else: rep["route"] = None
    return rep


