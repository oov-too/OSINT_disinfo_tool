    def stage_2_holds(self, source):
        """Stage 2 from a folder of holds (phase 7b, 2026-10-22): the holds are already records in the hold schema, so the hold schema
        is the mapping (each field its own; nothing to introspect or confirm column by column). The group names the set, sees the
        field coverage and five records (the dry run: each hold verified byte for byte against its hold.json), and the holds are
        copied into the project's sources/<set>/ (kept in place when they are already under sources/) before the scan runs over them."""
        A = self.answers
        root = os.path.abspath(os.path.expanduser(str(source)[6:] if str(source).startswith("holds:") else str(source)))
        folders = hold_folders(root)
        if not folders: raise Refusal(f"stage 2: no hold.json under {root}")
        name = A.get("2.name", "A short name for this set of holds (names it in the pack's [archives] and the status page)",
                     default=slug(os.path.basename(root), 40))
        recs = [(f, B.read_json(os.path.join(f, "hold.json"), {})) for f in folders]
        by_kind = collections.Counter((h.get("record") or {}).get("media_kind") or "?" for _, h in recs)
        cover = {fld: sum(1 for _, h in recs if (h.get("record") or {}).get(fld) not in (None, "", [], {})) for fld in S.FIELD_NAMES}
        missing = [(os.path.relpath(f, root), fld) for f, h in recs for fld in S.REQUIRED if not (h.get("record") or {}).get(fld)]
        if missing: raise Refusal("stage 2: holds without a required field (" + ", ".join(S.REQUIRED) + "): " + "; ".join(f"{a}: {b}" for a, b in missing[:10]))
        intro = {"source": "holds", "root": D_redact(root), "holds": len(folders), "by_kind": dict(by_kind), "field_coverage": cover,
                 "schemas": sorted({str(h.get("schema", "?")) for _, h in recs}), "adapters": sorted({str(h.get("adapter", "?")) for _, h in recs})}
        write_json(self.dir("introspection.json"), intro)
        rows = [[fld, "the hold's own record field (identity)", f"{cover[fld]} of {len(folders)}", S.BY_NAME[fld]["meaning"]] for fld in S.FIELD_NAMES]
        write(self.dir("mapping.md"), f"# Mapping of the holds under {D_redact(root)} (setup stage 2)\n\nThe source is a folder of holds already in the hold "
              "schema (tools/hold-schema.md), so each field maps to itself; the table shows how many holds carry it.\n\n"
              + md_table(["Hold field", "From", "Holds carrying it", "Meaning"], rows) + "\n\nBy media kind: "
              + ", ".join(f"{k} {v}" for k, v in sorted(by_kind.items())) + ".")
        dry = []
        for f, h in recs[:5]:
            r = h.get("record") or {}
            dry.append({"identifier": r.get("identifier"), "title": r.get("title"), "date": r.get("date"), "media_kind": r.get("media_kind"),
                        "text": r.get("text") or "none", "files": len(h.get("files", [])), "hold": os.path.relpath(f, root),
                        "status": "intact" if not B.verify_hold(f) else "PROBLEMS: " + "; ".join(B.verify_hold(f))[:200]})
        cols = ("identifier", "title", "date", "media_kind", "text", "files", "hold", "status")
        write(self.dir("dry-run.md"), "# Dry run of five holds (setup stage 2)\n\nEach hold verified against its hold.json (every file's bytes and SHA-256, the "
              "generated README); nothing is copied until the holds are accepted.\n\n" + md_table(["Identifier", "Title", "Date", "Kind", "Text", "Files", "Hold", "Status"], [[r[k] for k in cols] for r in dry]))
        ok = A.get("2.dry_run_ok", f"{len(folders)} holds found under {root} ({', '.join(f'{k} {v}' for k, v in sorted(by_kind.items()))}); five shown in "
                   "setup/dry-run.md, each verified. Do they look right?", kind="bool", context={"dry_run": dry, "field_coverage": cover})
        if not ok: raise Refusal("stage 2: the holds were not accepted; correct them (or choose another source) and run stage 2 again")
        hold_now = A.get("2.hold_now", f"Copy the holds into this project's sources/{name}/ (each verified after the copy; holds already under sources/ stay "
                         "where they are) and run the setup scan over them?", kind="bool", default=True)
        placed, problems, sc = [], [], None
        inside = os.path.realpath(root).startswith(os.path.realpath(self.p("sources")) + os.sep)   # already this project's holds: used in place
        hold_rel = os.path.relpath(root, self.project).replace(os.sep, "/") if inside else f"sources/{name}"
        if hold_now:
            for f in folders:
                dst = f if inside else self.p("sources", name, os.path.relpath(f, root))   # sources/<set>/..., as a database's holds go to sources/db/<name>/
                if not inside:
                    if os.path.exists(dst):
                        if B.read_json(os.path.join(dst, "hold.json"), {}) != B.read_json(os.path.join(f, "hold.json"), {}):
                            problems.append(f"{os.path.relpath(dst, self.project)}: a different hold is already there (left as it is)")
                    else:
                        shutil.copytree(f, dst)
                bad = B.verify_hold(dst)
                if bad: problems.append(f"{os.path.relpath(dst, self.project)}: " + "; ".join(bad))
                placed.append(dst)
            if problems: raise Refusal("stage 2: holds failed verification after the copy: " + "; ".join(problems[:10]))
            pirs = self.pack().get("pirs", {}).get("pir", [])
            sc = scan(self.project, name, pirs, folders=placed)
            write_json(self.dir("scan.json"), sc)
            write(self.dir("scan.md"), scan_markdown(sc))
        pack = self.pack()
        pack["archives"] = {"holds": [{"name": name, "source": D_redact(root), "mapping": "the hold schema (tools/hold-schema.md): each field its own",
                                       "hold": hold_rel, "holds": len(folders), "by_kind": dict(by_kind),
                                       "reread": "hold new sources through `ledger acquire` (web, document, canon, batch); a hold set has no live source to re-read"}]}
        pack["metadata"] = {"kept": [], "promoted": []}
        pack.setdefault("registers", {})["import"] = []
        slots = self.slots()
        slots["archives"] = (f"the set {name}: {len(folders)} holds already in the hold schema ({', '.join(f'{k} {v}' for k, v in sorted(by_kind.items()))}), "
                             f"held under {hold_rel}/; each hold's hold.json is its record and README.md its human form")
        self.pack_answers(2, pack, slots)
        self.write_keywords(pack)   # the scan's names, organisations, polities, aliases and identifier forms
        self.write_pack(pack, slots)
        self.write_ledger({"database": {"source": "holds:" + D_redact(root), "mapping": "the hold schema", "name": name}})
        return self.write_stage(2, {"source": "holds", "set": name, "holds": len(folders), "by_kind": dict(by_kind), "held": len(placed),
                                    "copied": 0 if inside else len(placed), "hold": hold_rel,
                                    "dry_run_records": len(dry), "scan_records": sc["records"] if sc else 0, "field_coverage": cover})

    def mapping_markdown(self, m, rep, rescan=None):
        rows = []
        for f in S.FIELD_NAMES:
            spec = m["fields"].get(f)
            if not spec: rows.append([f, S.BY_NAME[f]["required"], "(none proposed)", "", "", ""]); continue
            alts = spec.get("alternatives")
            ordered = isinstance(alts, list) and alts and all(isinstance(a, dict) for a in alts)
            if ordered:   # sources tried in order per record (the text, a split date)
                from ledger.acquire import database as D
                expr = " then ".join(f"({i}) {D.spec_label(a, m['record']['table'])}" for i, a in enumerate(alts, 1))
            else:
                expr = spec.get("column") or (", ".join(spec["columns"]) + f" split {spec.get('split')!r}" if spec.get("columns") else None) \
                    or (json.dumps(dict(spec["segments"]), ensure_ascii=False) if spec.get("segments") else None) or spec.get("template") \
                    or (f"value {spec['value']!r}" if "value" in spec else None) or spec.get("fallback") or spec.get("sql") or ""
            rows.append([f, S.BY_NAME[f]["required"], expr, spec.get("confidence", ""), spec.get("why", ""),
                         spec.get("candidates", []) if ordered else (alts or [])])
        out = ["# Proposed mapping (setup stage 2)", "", f"Database {m['mapping']['database']} ({m['mapping']['engine']}); {len(rep['tables'])} tables; "
               f"fingerprint {rep['fingerprint'][:12]}. Confirm or edit each row; nothing is held in the hold proper before the dry run.", "",
               f"Record unit: **{m['record']['table']}** keyed by {m['record']['key']} (confidence {m['record']['confidence']}; {m['record']['why']}); "
               f"alternatives: {', '.join(m['record']['alternatives']) or 'none'}.", "",
               md_table(["Hold field", "Required", "Column or expression", "Confidence", "Evidence", "Alternatives"], rows), "",
               "Media: " + ("; ".join(f"{x['table']}.{x.get('path') or x.get('url') or x.get('blob')} ({x.get('why', '')})" for x in m.get("media", [])) or "none"), "",
               "Unmapped columns kept as metadata: " + (", ".join(m.get("metadata", {}).get("columns", [])) or "none"), "",
               "Annotation tables offered for import: " + ("; ".join(f"{a['table']} -> {a.get('register')} (teller: {a['teller']}; {a['reading']})" for a in m.get("annotations", [])) or "none"), "",
               "Not read: " + ("; ".join(f"{x['table']} ({x['reason']})" for x in m.get("ignored", [])) or "none"), "", "## Tables", ""]
        for t in rep["tables"]:
            out.append(f"### {t['name']} ({t['rows']} rows)")
            out.append(md_table(["Column", "Type", "Key", "Nulls", "Distinct", "Samples"],
                                [[c["name"], c["declared_type"], "pk" if c["pk"] else "", c["null_share"], c["distinct"], c["samples"][:3]] for c in t["columns"]]))
            out.append("")
        if rescan:
            out += ["## Re-scan against the mapping saved before", "", "```", json.dumps(rescan, indent=1, ensure_ascii=False), "```", ""]
        return "\n".join(out)

