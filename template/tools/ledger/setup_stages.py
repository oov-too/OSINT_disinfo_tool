def md_cell(v):
    if isinstance(v, (list, tuple)): v = "; ".join(map(str, v))
    return str(v if v is not None else "").replace("|", "/").replace("\n", " ")


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for r in rows: out.append("| " + " | ".join(md_cell(c) for c in r) + " |")
    return "\n".join(out)


def _strip_none(x):
    if isinstance(x, T.Inline): return T.Inline({k: _strip_none(v) for k, v in x.items() if v is not None})
    if isinstance(x, dict): return {k: _strip_none(v) for k, v in x.items() if v is not None}
    if isinstance(x, list): return [_strip_none(v) for v in x if v is not None]
    return x


def _tomlable(x):
    """Turn answers (lists of dicts, nested dicts) into what the small TOML writer takes: dicts inside an array of tables become
    inline tables, lists of dicts inside an inline value stay inline."""
    if isinstance(x, dict): return {k: _tomlable_value(v) for k, v in x.items()}
    return x


def _tomlable_value(v):
    if isinstance(v, dict): return {k: _tomlable_value(x) for k, x in v.items()}
    if isinstance(v, list) and v and all(isinstance(i, dict) for i in v):
        return [{k: (T.Inline(_inline(x)) if isinstance(x, dict) else _inline(x)) for k, x in i.items()} for i in v]
    return v


def _inline(v):
    if isinstance(v, dict): return T.Inline({k: _inline(x) for k, x in v.items()})
    if isinstance(v, list): return [_inline(x) for x in v]
    return v


