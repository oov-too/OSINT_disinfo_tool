#!/usr/bin/env python3
"""Write research/<prefix>-charts.md (the per-interview candour charts page) from the chart JSONs in research/figures/.
The candour audit was renamed on 2026-10-22 (tools/schema.md section 3); the term, the file prefix and the page's prose are the pack's
display settings (pack.toml [display.candour]; core defaults "Candour" and "candour" in tools/packload.py), so a pack that keeps the
legacy term keeps its file names and wording.

Run after drawing charts (tools/draw_forthrightness_chart.py --overview calls it at the end):
    python3 tools/build_forthrightness_page.py
Sections: metadata, scope and reading rules, the by-interviewee ranking, the closed-subtle ranking with each interviewee's
topics as sub-lines (a fixed-width block so the sub-lines never wrap), and the by-recording ranking.
Reads research/figures/<prefix>-groups.json, <prefix>-by-interviewee.json and <prefix>-<stem>.json.
"""
import json, re, os, sys
import sys as _sys; _T = os.path.dirname(os.path.abspath(__file__)); _sys.path.insert(0, _T) if _T not in _sys.path else None   # the ledger package beside this tool
from ledger.paths import root as _project_root; ROOT = _project_root()   # $LEDGER_ROOT, else the nearest ledger.toml at or above the working folder, else this tools' project (2026-10-22); os.chdir(ROOT); sys.path.insert(0,"tools")
from ledger import notes as LN   # the parser library: LF writes (tools/ledger/notes.py, phase 2)
import packload   # topic labels, short labels and the page's wording (pack.toml [audit.topics], [display.index], [display.candour]; phase 5)
C=packload.display("candour"); PX=C["file_prefix"]
FIG="research/figures"
LABEL=dict(packload.topic_labels()); LABEL.update(C["page_labels"])
SHORT=packload.short_labels()
_jl=lambda p, empty: json.load(open(p,encoding="utf-8")) if os.path.exists(p) else empty   # a new project has no chart data yet (phase 7b)
groups=_jl(f"{FIG}/{PX}-groups.json",[])
ov={r["label"]:r for r in _jl(f"{FIG}/{PX}-by-interviewee.json",[])}
def stem(g): return ("person-"+re.sub(r"[^a-z0-9]+","-",g["label"].lower()).strip("-")) if len(g["slugs"])>1 else g["slugs"][0]
def cnt(c,k): return c.get(k,0)
L=["# "+C["page_title"],"",
"| Field | Value |","|---|---|","| **Kind** | research |",f"| **Built** | generated by tools/build_forthrightness_page.py from the chart JSONs |",
"| **Tool** | `python3 tools/draw_forthrightness_chart.py <slug>` (one recording); `--group \"<Label>\" <slug> ...` (one interviewee, recordings pooled, one strip per recording); `--overview` (every interviewee ranked, from "+f"research/figures/{PX}-groups.json; also rewrites this page). Reads notes.db only. |",
f"| **Overview** | [{PX}-by-interviewee.png](figures/{PX}-by-interviewee.png) ([json](figures/{PX}-by-interviewee.json)) |",
"| **Related** | "+(C.get("page_related") or f"[openness map](openness-map.md) (the whole-database chart, drawn only by tools/draw_openness_map.py); {C['heading_note']}; [topic corroboration](topic-corroboration.md)")+" |",
"","Same classes, colours, closure index and zone bands as the openness map, applied to one recording's audit table or to one interviewee's pooled audits. Each single chart has three panels: the whole recording as one 100%-share bar with the closure index diamond; the topics touched, most open at the top (each audit row takes the topic of the claims rows that cite it as \"Audit N\", or that share its timestamp); and a turn-by-turn strip through the recording showing where the closures fall, with stated declines marked below. Pooled charts add one strip per recording so a voice can be read across its interviews.","",
C["page_scope"],"",
C["page_reading"],"",
"## By interviewee (pooled), most open first","",
"| Interviewee | Chart | Recordings | Scored turns | Open / partial / closed-subtle / closed-outright | Stated declines | Closure index |","|---|---|---|---|---|---|---|"]
for r in sorted(ov.values(),key=lambda r:r["index"]):
    g=next(g for g in groups if g["label"]==r["label"]); c=r["counts"]
    L.append(f"| {r['label']} | [chart](figures/{PX}-{stem(g)}.png) | {len(g['slugs'])} | {r['scored']} | {cnt(c,'open')} / {cnt(c,'partial')} / {cnt(c,'closed-subtle')} / {cnt(c,'closed-outright')} | {r['declines']} | {r['index']:.2f} |")
# closed-subtle ranking with topic sub-lines
rows=[]
for g in groups:
    r=ov.get(g["label"]); p=f"{FIG}/{PX}-{stem(g)}.json"
    if not r or not os.path.exists(p): continue
    j=json.load(open(p,encoding="utf-8"))
    bt=sorted([(LABEL.get(t,t),c.get("closed-subtle",0)) for t,c in j["by_topic"].items() if c.get("closed-subtle",0)],key=lambda x:(-x[1],x[0].startswith("Other"),x[0]))
    k=len(g["slugs"]); name=g["label"]+(f" ({k} recordings)" if k>1 and not any(w in g["label"] for w in C["one_voice_labels"]) else "")   # a group the pack counts as one voice (a channelled series) gets no recordings count
    rows.append((cnt(r["counts"],"closed-subtle"),r["scored"],name,cnt(r["counts"],"closed-outright"),bt))
rows.sort(key=lambda t:(-t[0],-(t[0]/t[1] if t[1] else 0),t[2]))
NW=max((len(x[2]) for x in rows),default=0); NW=max(NW,max((len(t)+4 for x in rows for t,_ in x[4]),default=0))
hdr=f"{'Rank':>4}  {'Interviewee, then topics closed subtly':<{NW}}  {'Subtle':>6}  {'Turns':>5}  {'Share':>6}  {'Outright':>8}"
B=[hdr,"-"*len(hdr)]; rank=0; prev=None
for i,(cs,n,name,co,bt) in enumerate(rows):
    if cs!=prev: rank=i+1; prev=cs
    B.append(f"{rank:>4}  {name:<{NW}}  {cs:>6}  {n:>5}  {cs/n*100:>5.1f}%  {co:>8}")
    for t,k in bt: B.append(f"{'':>4}    └ {t:<{NW-4}}  {k:>6}")
L+=["","## Closed-subtle ranking, with the topics each voice slides away from","",
"Interviewees ranked by closed-subtle turns (the audit's \"slid away, redirected, dropped\" class), most first; ties broken by share of scored turns. Under each interviewee, the topics those turns fall on, most frequent first. Share is closed-subtle as a percentage of the voice's scored turns; Outright is closed-outright turns for comparison. A raw count favours voices with long or several recordings, so read Share alongside it. Topic assignment comes from the claims ledger's \"Audit N\" pointers and shared timestamps; \""+LABEL.get("other","Other")+"\" means the audit row had neither, and is a gap in the join, not a topic.","",
"```",*B,"```"]
if C["page_ranking_note"]: L+=["",C["page_ranking_note"]]
L+=["","## By recording, most open first","","| Recording | Chart | Scored turns | Open / partial / closed-subtle / closed-outright | Stated declines | Closure index |","|---|---|---|---|---|---|"]
recs=[]
for g in groups:
    for s in g["slugs"]:
        p=f"{FIG}/{PX}-{s}.json"
        if not os.path.exists(p): continue
        j=json.load(open(p,encoding="utf-8")); c=j["counts"]
        recs.append((j["closure_index"],f"| [{SHORT.get(s+'.md',s)}](../videos/{s}.md) | [chart](figures/{PX}-{s}.png) | {j['scored']} | {cnt(c,'open')} / {cnt(c,'partial')} / {cnt(c,'closed-subtle')} / {cnt(c,'closed-outright')} | {j['stated_declines']} | {j['closure_index']:.2f} |"))
L+=[r for _,r in sorted(recs)]
if C["page_closing"]: L+=["",C["page_closing"]]
out=f"research/{PX}-charts.md"
LN.write_text(out,"\n".join(L)+"\n")
print(f"wrote {out}:",len(ov),"interviewees,",len(recs),"recordings; closed-subtle block width",len(hdr))
