#!/usr/bin/env python3
"""Write research/status.md, the status page regenerated after every hand-back (tools/platform-plan.md, phase 7 interface: "a status
doc republished after every hand-back"; phase 5 builds it as a local markdown page; wip/platform-phase4/skills.md, /status).

Usage: python3 tools/build_status.py [--out research/status.md] [--db notes.db]

Sections, each from what the folder already holds (nothing here is a judgement of its own):
  sources held and queued   the sources/ layout's alias table and the files held under sources/ by media kind; notes by source kind
                            (tools/source_balance.py's kinds); queued records (every sources/**/queue.tsv) and open blocked passages
  notes written             notes.db: notes by folder, research pages, subject pages, narrative pages, words
  register sizes            notes.db tables; the actor and polity register's rows and statements (graph-typed.json, when built)
  not held                  research/first-utterance.md (the pack's [catalysts] report): the clusters the narrative pages rest on whose
                            first telling is not held (late, candidate not held, known earlier not held)
  quota ledger              tools/source_balance.py's own lines (read-only run)
  open rulings              the rulings log (pack [display.status] rulings_log, default rulings.md) if present, else a placeholder
  priority intelligence     the pack's declared PIRs ([[pirs.pir]]: id, question, eeis, terms) and the held rows naming each (rows_fts)
  sample readings           every note's sample tally (`sample: meaning M of 20 ...`, `none` before the phase) and the total per run,
                            from the cost log's sample lines (`ledger integrate`, tools/ledger/sample.py)
  cost log                  the cost log (pack [display.status] cost_log) if tools/agent_usage.py's output was saved there
Plain markdown, LF, no external links (the page is read on a network with no outside reach): an address in a quoted row (a register
cell naming a source's URL, say) is reduced to its host, and a markdown link to its label."""
import os, re, sys, glob, json, sqlite3, datetime, subprocess, collections
import sys as _sys; _T = os.path.dirname(os.path.abspath(__file__)); _sys.path.insert(0, _T) if _T not in _sys.path else None   # the ledger package beside this tool
from ledger.paths import root as _project_root; ROOT = _project_root()   # $LEDGER_ROOT, else the nearest ledger.toml at or above the working folder, else this tools' project (2026-10-22); os.chdir(ROOT); sys.path.insert(0, "tools")
from ledger import notes as LN, paths as LP   # the parser library and the sources/ layout (phase 2)
import packload   # titles, paths and the PIRs (pack.toml [display.status], [catalysts], [pirs])

if "-h" in sys.argv or "--help" in sys.argv: print(__doc__); sys.exit(0)
def arg(n, d): return sys.argv[sys.argv.index(n) + 1] if n in sys.argv else d
OUT = arg("--out", "research/status.md"); DB = arg("--db", packload.ledger()["database"]["path"])
S = packload.display("status"); PK = packload.pack(); OBJ = packload.objects()
today = datetime.date.today().isoformat()
con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
def q1(sql, *a):
    try: return con.execute(sql, a).fetchone()[0]
    except sqlite3.Error: return None
URL = re.compile(r"(?:https?|ftp)://([^/\s)|\]>\"']+)[^\s)|\]>\"']*", re.I)
HOST = lambda m: re.sub(r"^www\.", "", m.group(1), flags=re.I)   # without "www." a host is not autolinked by markdown renderers either
def unlink(t):
    """A quoted row's links made plain: a markdown link keeps its label, a bare address keeps only its host, with no scheme (the page
    is read with no outside reach and carries no external links; a register row may hold a source's address)."""
    return URL.sub(HOST, re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", str(t or "")))
def cell(t, n=160): return re.sub(r"\s+", " ", unlink(t)).replace("|", "/").strip()[:n]
L = [f"# {S['title']}", "", "| Field | Value |", "|---|---|",
     "| **Kind** | derived page, generated by `tools/build_status.py` after every hand-back; do not edit by hand |",
     f"| **Built** | {today} |", f"| **Pack** | {PK['pack']['name']} ({packload.ledger()['pack']['path']}) |",
     f"| **Database** | {DB}, built {datetime.datetime.fromtimestamp(os.path.getmtime(DB)).strftime('%Y-%m-%d %H:%M')} |" if os.path.exists(DB) else f"| **Database** | {DB} (not built) |", ""]

# ---- sources held and queued
L += ["## Sources held and queued", ""]
al = LP.aliases(); kinds = collections.Counter(); folders = collections.Counter()
for a in al: (folders if a.endswith("/") else kinds)[a.split("/")[1] if a.count("/") >= 2 else "other"] += 1
held = collections.Counter()
for p in glob.glob("sources/*/**/*", recursive=True):
    if os.path.isfile(p) and not os.path.basename(p).startswith("."): held[p.split("/")[1]] += 1
L += ["Held, by media kind (the sources/ layout of tools/ledger/paths.py: files that keep their old place are reached through the alias table; folders are aliased whole):", "",
      "| Media kind | Files aliased | Folders aliased | Files held under sources/ |", "|---|---|---|---|"]
for k in sorted(set(kinds) | set(folders) | set(held)): L.append(f"| {k} | {kinds.get(k, 0)} | {folders.get(k, 0)} | {held.get(k, 0)} |")
try:
    import source_balance as SB
    ov = SB.overrides(); bykind = collections.Counter()
    for vid, ch in con.execute("select id, channel from videos"): bykind[ov.get(vid) or SB.guess(vid, ch)] += 1
    L += ["", "Notes by source kind (tools/intake-policy.md; research/source-kinds.md overrides, else the pack's stem patterns):", "", "| Kind | Notes |", "|---|---|"]
    L += [f"| {k} | {bykind.get(k, 0)} |" for k in packload.source_kinds()] + [f"| {k} | {v} |" for k, v in bykind.items() if k not in packload.source_kinds()]
except Exception as e: L += ["", f"Notes by source kind: not computed ({e})."]
queues = sorted(glob.glob("sources/**/queue.tsv", recursive=True)); qrows = 0; qlines = []
for qp in queues:
    n = max(0, sum(1 for l in LN.read_lines(qp) if l.strip() and not l.startswith("#")) - 1); qrows += n; qlines.append(f"| {qp} | {n} |")
blocked = "research/corrections/blocked-passages.md"; bopen = 0
if os.path.exists(blocked):
    for l in LN.iter_lines(blocked):
        c = LN.split_row(l) if l.startswith("|") else []
        if len(c) >= 8 and re.match(r"BP-\d+", c[0]) and c[7].strip().lower().startswith("open"): bopen += 1
L += ["", f"Queued: {qrows} record{'s' if qrows != 1 else ''} in {len(queues)} queue file{'s' if len(queues) != 1 else ''} (the database adapter's new and changed records); {bopen} open blocked passage{'s' if bopen != 1 else ''} ({blocked}).", ""]
if qlines: L += ["| Queue | Records |", "|---|---|", *qlines, ""]

# ---- notes written
nd = collections.Counter((f or "").split("/")[0] for (f,) in con.execute("select file from videos")) if q1("select count(*) from videos") is not None else {}
L += ["## Notes written", "", "| What | Count |", "|---|---|"]
for k, v in sorted(nd.items()): L.append(f"| notes in {k}/ | {v} |")
L += [f"| research pages (pages table) | {q1('select count(*) from pages') or 0} |", f"| subject pages | {len(glob.glob(os.path.join(PK['subjects'].get('pages_dir', 'subjects'), '*.md')))} |",
      f"| narrative pages (narratives table) | {q1('select count(*) from narratives') or 0} |", f"| words in the notes | {q1('select sum(words) from videos') or 0:,} |", ""]

# ---- register sizes
REG = [("claims", "claims rows"), ("quotes", "quotes"), ("timeline", "dated timeline rows"), ("cross_checks", "cross-checks"), ("audit_rows", "candour audit rows"),
       ("open_questions", "open questions (notes)"), ("leads", "leads register"), ("relations", "relations register"), ("register", OBJ["watch_name"].replace(" watch", "") + " register (object register)"),
       (packload.name("table.object_watch"), OBJ["watch_name"] + " rows (object watch)"), ("mentions", "people mentions"), ("people", "people"), ("works", "works cited"), ("tracker", "ties tracker"),
       ("narrative_nodes", "narrative nodes"), ("narrative_contradictions", "narrative contradiction rows"), ("owner_notes", "owner's map notes"), ("owner_investigations", "owner's investigations")]
L += ["## Register sizes", "", "| Register | Rows |", "|---|---|"]
for t, lab in REG:
    n = q1(f"select count(*) from [{t}]")
    if n is not None: L.append(f"| {lab} | {n:,} |")
tg = "research/figures/graph-typed.json"
if os.path.exists(tg):
    m = json.load(open(tg, encoding="utf-8")).get("meta", {})
    L += [f"| actor register rows ({m.get('register', '')}) | {m.get('register_rows', 0):,} |", f"| polity statements | {m.get('polity_statements', 0):,} |",
          f"| order-of-battle placements / chain hops (graph-typed.json) | {m.get('placements', 0):,} / {m.get('hops', 0):,} |"]
fur = PK.get("catalysts", {}).get("register")
if fur and os.path.exists(fur): L.append(f"| first-utterance clusters ({fur}) | {sum(1 for l in LN.iter_lines(fur) if re.match(r'\| FU-\d+', l))} |")
L.append("")

# ---- what the narratives rest on that is not held
NOT_HELD = ("late", "candidate not held", "known earlier not held")
fu = PK.get("catalysts", {}).get("report", "research/first-utterance.md")
L += ["## What the narratives rest on that is not held", ""]
if os.path.exists(fu):
    lines = LN.read_lines(fu); built = next((l for l in lines[:6] if l.startswith("Built")), "")
    summary, clusters, page = [], {}, None
    for l in lines:
        if l.startswith("## "): page = l[3:].split(":")[0].strip(); continue
        if not l.startswith("|"): continue
        c = LN.split_row(l)
        if page is None and c and c[0] not in ("Page",) and not set(c[0]) <= set("-: ") and len(c) >= 8: summary.append(c)
        elif page and len(c) >= 8 and re.match(r"FU-\d+", c[1] or "") and c[7].strip() in NOT_HELD:
            d = clusters.setdefault(c[1], dict(status=c[7].strip(), event=c[2], held=c[3], known=c[4], pages=set())); d["pages"].add(page)
    hdr = next((LN.split_row(l) for l in lines if l.startswith("| Page")), [])
    idx = {h: i for i, h in enumerate(hdr)}
    L += [f"From {fu} ({cell(built, 60) or 'undated'}). A cluster is not held when its first telling is not in the database: `late` (no held telling before the threshold catalyst and no earlier telling recorded), `candidate not held` (an earlier telling is proposed, not held), `known earlier not held` (an earlier telling is named; intake it).", "",
          "| Page | Nodes | " + " | ".join(NOT_HELD) + " | not held |", "|---|---|" + "---|" * (len(NOT_HELD) + 1)]
    for c in summary:
        v = [int(c[idx[k]]) if k in idx and c[idx[k]].isdigit() else 0 for k in NOT_HELD]
        L.append(f"| {c[0]} | {c[1]} | " + " | ".join(map(str, v)) + f" | {sum(v)} |")
    L += ["", f"{len(clusters)} distinct clusters not held, the most-used first:", "", "| Cluster | Status | Event | Earliest held | Earliest known | Pages |", "|---|---|---|---|---|---|"]
    for k, d in sorted(clusters.items(), key=lambda kv: (-len(kv[1]["pages"]), int(kv[0].split("-")[1]))):
        L.append(f"| {k} | {d['status']} | {cell(d['event'], 60)} | {cell(d['held'], 80)} | {cell(d['known'], 90)} | {len(d['pages'])}: {', '.join(sorted(d['pages']))} |")
    L.append("")
else: L += [f"No first-utterance report ({fu}); run `python3 tools/first_utterance.py --narratives`.", ""]

# ---- quota ledger
L += ["## Quota ledger", ""]
try:
    r = subprocess.run([sys.executable, os.path.join(_T, "source_balance.py")], capture_output=True, text=True, timeout=600)
    L += [f"From `tools/source_balance.py` (tools/intake-policy.md rule 6; read-only run, exit {r.returncode}):", ""] + [f"- {cell(l, 400)}" for l in r.stdout.split("\n") if l.strip()] + [""]
except Exception as e: L += [f"Not computed: {e}", ""]

# ---- open rulings
RL = S["rulings_log"]
L += ["## Open rulings", ""]
if os.path.exists(RL):
    opens = []; sec = ""
    for l in LN.iter_lines(RL):
        if l.startswith("#"): sec = l.lstrip("# ").strip(); continue
        if l.startswith("|"):
            c = LN.split_row(l)
            if any(x.strip().lower() in ("open", "pending", "proposed") for x in c): opens.append(" / ".join(cell(x, 120) for x in c if x.strip()))
        elif re.match(r"\s*[-*]\s.*\b(open|pending|proposed)\b", l, re.I): opens.append(cell(l.lstrip(" -*"), 300))
    L += [f"From {RL}: {len(opens)} open." , ""] + [f"- {o}" for o in opens] + [""]
else:
    L += [f"No rulings log ({RL}) in this folder yet: phase 7 adds one (each ruling with its author and date, binding only from the members the pack names). Until then the rulings stand in tools/platform-plan.md and the owner's instructions.", ""]

# ---- priority intelligence requirements
L += ["## Priority intelligence requirements", ""]
PIRS = packload.pirs()
if not PIRS: L += ["The pack declares none (pack.toml `[[pirs.pir]]`: id, question, eeis, terms, declared, by); /setup stage 1 records them. A PIR seeds keywords and surfaces held rows; it never places anything the sources do not support.", ""]
for p in PIRS:
    terms = [t for t in p.get("terms", []) if t.strip()]
    L += [f"### {p.get('id', '?')}: {cell(p.get('question', ''), 300)}", "", f"Declared {p.get('declared', 'undated')} by {p.get('by', 'not recorded')}. Essential elements of information: " + ("; ".join(cell(e, 200) for e in p.get("eeis", [])) or "none listed") + ".", ""]
    if not terms: L += ["No terms declared, so no rows are surfaced.", ""]; continue
    match = " OR ".join('"' + t.replace('"', '') + '"' for t in terms)
    try:
        rows = con.execute("select kind, video, n, date, speaker, text from rows_fts where rows_fts match ? order by rank", (match,)).fetchall()
    except sqlite3.Error as e: L += [f"Rows not searched: {e}", ""]; continue
    byk = collections.Counter(r[0] for r in rows)
    L += [f"Held rows naming it (rows_fts: {match}): {len(rows)} ({', '.join(f'{k} {v}' for k, v in byk.most_common()) or 'none'}).", ""]
    if rows: L += ["| Kind | Note | Row | Date | Speaker | Text |", "|---|---|---|---|---|---|"] + [f"| {r[0]} | {r[1]} | {r[2]} | {cell(r[3], 20)} | {cell(r[4], 40)} | {cell(r[5], 200)} |" for r in rows[:25]] + [""]

# ---- sample readings (2026-10-25: the sample reading is a phase of every intake; `ledger integrate` writes each task's tally as a
# line of the cost log, tools/ledger/sample.py; a note integrated before the phase, or with sample false, shows `none`)
CL = S["cost_log"]
L += ["## Sample readings", ""]
try:
    from ledger import sample as SM
    reads = SM.cost_log_readings(CL)
    notes_all = [f for (f,) in con.execute("select file from videos order by file")] if q1("select count(*) from videos") is not None else []
    MR = re.compile(r"meaning (\d+) of (\d+)")
    runs = collections.OrderedDict()
    for nf, (task, run, day, res) in reads.items():
        m = MR.search(res); after = re.search(r"after the check: meaning (\d+) of (\d+)", res)
        if not m: continue
        r = runs.setdefault(run, [0, 0, 0, 0, 0])   # notes, meaning, rows, notes at the threshold, meaning after the redraw
        r[0] += 1; r[1] += int(m.group(1)); r[2] += int(m.group(2)); r[3] += 1 if "threshold" in res else 0; r[4] += int(after.group(1)) if after else 0
    L += [f"The tally of each note's twenty sampled claims rows (faults of meaning first; tools/ledger/sample.py, written to {CL} by `ledger integrate`); "
          "`none` for a note integrated before the phase or without it.", "", "| Note | Sample |", "|---|---|"]
    L += [f"| {nf} | {cell(reads[nf][3], 300) if nf in reads else 'none'} |" for nf in notes_all]
    L += [f"| {nf} (not in the database) | {cell(v[3], 300)} |" for nf, v in reads.items() if nf not in notes_all]
    tn = sum(r[0] for r in runs.values()); tm = sum(r[1] for r in runs.values()); tr = sum(r[2] for r in runs.values())
    L += ["", "| Run | Notes read | Meaning | Rows | At the threshold |", "|---|---|---|---|---|"] + [f"| {cell(k, 60)} | {v[0]} | {v[1]} | {v[2]} | {v[3]} |" for k, v in runs.items()]
    L += [f"| **total** | {tn} | {tm} | {tr} | {sum(r[3] for r in runs.values())} |", "",
          f"Sample total: meaning {tm} of {tr} rows over {tn} note{'s' if tn != 1 else ''}; {len(notes_all) - sum(1 for nf in notes_all if nf in reads)} note(s) `none`.", ""]
except Exception as e: L += [f"Not computed: {e}", ""]

# ---- cost log
L += ["## Cost log", ""]
if os.path.exists(CL):
    cl = [l for l in LN.read_lines(CL) if l.strip()]
    L += [f"From {CL} (tools/agent_usage.py), the last rows:", ""] + [l for l in cl if l.startswith("|")][:2] + [l for l in cl if l.startswith("|")][2:][-20:] + [""]
else: L += [f"No cost log ({CL}): tools/agent_usage.py prints each run's usage (`--md` for the table); save it there to have it summarised here.", ""]

text = "\n".join(L).rstrip("\n") + "\n"
_n = len(URL.findall(text)); text = URL.sub(HOST, text)   # anything copied whole (a cost log or rulings row) is unlinked too
if _n: print(f"build_status: {_n} address(es) outside the quoted cells reduced to their host")
LN.write_text(OUT, text)
print(f"wrote {OUT}: {len(L)} lines; {sum(held.values())} files under sources/, {qrows} queued, {bopen} blocked open; PIRs {len(PIRS)}")
