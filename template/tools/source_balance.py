#!/usr/bin/env python3
"""Source balance and the intake quota (tools/intake-policy.md rule 6). Usage: python3 tools/source_balance.py [--since 2026-10-14] [--write-kinds]
Reads notes.db (videos, claims) and research/source-kinds.md (overrides: | stem | kind | note |). Prints notes by kind, claims by source class,
and the quota ledger since the policy date (compiler intakes against document and adverse intakes). --write-kinds regenerates
research/source-kinds.md from the stem patterns, keeping existing override rows."""
import re, sys, os, sqlite3, collections, datetime
import sys as _sys; _T = os.path.dirname(os.path.abspath(__file__)); _sys.path.insert(0, _T) if _T not in _sys.path else None   # the ledger package beside this tool
from ledger.paths import root as _project_root; ROOT = _project_root()   # $LEDGER_ROOT, else the nearest ledger.toml at or above the working folder, else this tools' project (2026-10-22); os.chdir(ROOT); sys.path.insert(0, "tools")
from ledger import notes as LN   # the parser library (tools/ledger/notes.py, phase 2)
import packload   # the kinds are core; the stem patterns, policy date and baseline ratio are the pack's (pack.toml [source_kinds]; moved 2026-10-22)
KINDS = packload.source_kinds()
_PAT = packload.stem_patterns(); _DEFAULT = packload.default_kind(); _SK = packload.pack()["source_kinds"]
def guess(stem, channel):
    """The kind for a stem research/source-kinds.md does not list: the pack's stem patterns in order (compiler, document, host, witness, text documents), else the default."""
    s = stem
    if s.startswith(tuple(_PAT["compiler_prefix"])) or any(x in s for x in _PAT["compiler_contains"]) or s.endswith(tuple(_PAT["compiler_suffix"])): return "compiler"
    if s.startswith(tuple(_PAT["document_prefix"])): return "document"
    if s.startswith(tuple(_PAT["host_prefix"])): return "host"
    if any(x in s for x in _PAT["host_contains"]): return "host"
    if s.startswith(tuple(_PAT["witness_prefix"])): return "witness"
    if s.startswith(tuple(_PAT["text_document_prefix"])): return "document"
    return _DEFAULT
def overrides():
    d = {}
    if os.path.exists("research/source-kinds.md"):
        for line in LN.iter_lines("research/source-kinds.md"):
            m = re.match(r"\|\s*([a-z0-9-]+)\s*\|\s*([a-z-]+)\s*\|", line)
            if m and m.group(2) in KINDS: d[m.group(1)] = m.group(2)
    return d
def main():
    a = sys.argv[1:]; since = a[a.index("--since") + 1] if "--since" in a else _SK["policy_date"]
    con = sqlite3.connect("file:notes.db?mode=ro", uri=True); con.row_factory = sqlite3.Row
    ov = overrides(); rows = []
    for r in con.execute("select id, channel, added from videos"):
        k = ov.get(r["id"]) or guess(r["id"], r["channel"]); rows.append((r["id"], k, r["channel"] or "", r["added"] or ""))
    by = collections.Counter(k for _, k, _, _ in rows)
    print("notes by kind:", dict(by.most_common()))
    cls = collections.Counter(r["source_class"] for r in con.execute("select source_class from claims"))
    print("claims by source class:", dict(cls.most_common(8)))
    hostish = cls.get("host", 0) + cls.get("read", 0); prog = cls.get("program-record", 0)
    print(f"balance: host+read {hostish} : program-record {prog} = {round(hostish / max(1, prog), 1)} : 1 (policy baseline {_SK.get('baseline_ratio') or 'none set'})")
    recent = [(s, k, c, d) for s, k, c, d in rows if d >= since]
    q = collections.Counter(k for _, k, _, _ in recent)
    print(f"quota ledger since {since}: compiler {q.get('compiler', 0)}, document {q.get('document', 0)}, adverse {q.get('adverse', 0)}, earliest-telling {q.get('earliest-telling', 0)}, host {q.get('host', 0)}, witness {q.get('witness', 0)}")
    deficit_doc = max(0, q.get("compiler", 0) - q.get("document", 0)); deficit_adv = max(0, q.get("compiler", 0) - q.get("adverse", 0))
    print(f"quota deficit: {deficit_doc} document(s) and {deficit_adv} adverse source(s) owed before the next compiler intake")
    if "--write-kinds" in a:
        lines = ["# Source kinds (tools/intake-policy.md)", "", "Generated by tools/source_balance.py --write-kinds; rows are the tool's stem-pattern guess unless the Note column says `override`. Edit the Kind cell to override (kinds: compiler, host, witness, document, adverse, earliest-telling).", "", "| Stem | Kind | Channel | Note |", "|---|---|---|---|"]
        for s, k, c, d in sorted(rows): lines.append(f"| {s} | {k} | {c[:50]} | {'override' if s in ov else ''} |")
        LN.write_text("research/source-kinds.md", "\n".join(lines) + "\n"); print("written research/source-kinds.md")
if __name__ == "__main__": main()
